/**
 * Собственные размеры кадра — читаются из файла на сборке.
 *
 * Зачем. Рамка `MediaFrame` резервирует место соотношением, и до 2026-08-25
 * соотношение было выбором из двух: 16/9 или 3/4. Ни одно из них не совпадало
 * ни с одним реальным кадром кейса, а `object-fit: cover` разницу срезал —
 * молча и всегда. Замер: индекс двадцати экранов (0.58) показывался на треть,
 * рельс навигации — на три четверти по ширине, каждый снимок экрана (1.60)
 * терял по десятой части. Ошибка была не в кадрах, а в том, что рамка знала
 * о них только то, что они «широкие».
 *
 * Соотношение обязано приходить из самого файла. Тогда рамка не режет ничего
 * и резервировать место можно по-прежнему до загрузки: числа известны на
 * сборке, а не в браузере.
 *
 * Почему `sharp`, а не запись размеров руками в слое текстов: записанное
 * руками число расходится с файлом на первой же пересъёмке, и расходится
 * молча. `sharp` уже стоит в проекте — на нём собираются OG-карточки и
 * работает производство кадров (`scripts/shoot-case-frames.mjs`).
 *
 * Читается только на сборке: в браузер ни `sharp`, ни этот модуль не уходят.
 */
import path from 'node:path';
import process from 'node:process';

import sharp from 'sharp';

/**
 * Плотность, на которой производятся кадры — `scripts/shoot-case-frames.mjs`,
 * `deviceScaleFactor: 1.5`. Здесь она нужна, чтобы перевести пиксели файла в
 * пиксели раскладки: кадр, показанный крупнее, чем позволяет исходник, мылит
 * и ломает масштаб соседей. Рельс навигации — 390 px в файле, то есть 260 в
 * раскладке; в колонке 471 он растягивался вдвое, и его иконки выходили
 * крупнее иконок на соседнем снимке целого экрана.
 */
const FRAME_DENSITY = 1.5;

export interface FrameSize {
  width: number;
  height: number;
  /** Значение для `aspect-ratio`, готовое к подстановке в CSS. */
  ratio: string;
  /** Потолок ширины в пикселях раскладки: крупнее исходник не позволяет. */
  maxWidth: string;
}

/** Один файл читается один раз за сборку: на странице кейса кадров четырнадцать. */
const cache = new Map<string, FrameSize | null>();

/**
 * Размеры кадра по пути от корня сайта (`/media/...`).
 *
 * Возвращает `null` для всего, что не лежит в `public/` локальным растром:
 * внешние адреса, SVG-плейсхолдеры без собственных размеров, видео. Вызов
 * не бросает — отсутствие размеров означает «резервируй место как раньше»,
 * а не «ломай сборку»: кадр может быть заменён плейсхолдером по ходу работы.
 */
export async function frameSize(src: string): Promise<FrameSize | null> {
  if (!src.startsWith('/')) return null;
  if (cache.has(src)) return cache.get(src) ?? null;

  let size: FrameSize | null = null;

  try {
    const file = path.join(process.cwd(), 'public', src.replace(/^\//, ''));
    const { width, height } = await sharp(file).metadata();
    if (width && height) {
      size = {
        width,
        height,
        ratio: `${width} / ${height}`,
        maxWidth: `${Math.round(width / FRAME_DENSITY)}px`,
      };
    }
  } catch {
    size = null;
  }

  cache.set(src, size);
  return size;
}
