import fs from 'node:fs';
import { createRequire } from 'node:module';
const { chromium } = createRequire('D:/Claude-projects/Agent-ops-console/package.json')('playwright');
const browser=await chromium.launch();
const root='audit/vet-portfolio-premium-v3';
const results=[];
const key='vet-clinic-wire-data-v6';
fs.mkdirSync(`${root}/product-qa`,{recursive:true});
for(const locale of ['en','ru']) for(const width of [1440,390]) {
  const ctx=await browser.newContext({viewport:{width,height:900},reducedMotion:'reduce',timezoneId:'Europe/Moscow'});
  const page=await ctx.newPage();const entry={locale,width,tests:[],errors:[]};
  page.on('pageerror',e=>entry.errors.push(e.message));
  const test=(label,pass)=>{entry.tests.push({label,pass:!!pass}); if(!pass) console.log('FAIL',locale,width,label);};
  const route=s=>`http://127.0.0.1:5370/${locale==='ru'?'ru/':''}app/${s}?patient=marsik`;
  const go=async s=>{await page.goto(route(s),{waitUntil:'networkidle'});await page.evaluate(()=>document.fonts.ready);await page.waitForTimeout(700);};
  const state=()=>page.evaluate(k=>JSON.parse(localStorage.getItem(k)),key);
  const load=async(s,f)=>{await page.evaluate(({k,f})=>localStorage.setItem(k,JSON.stringify(f)),{k:key,f});await go(s);};
  await go('visit-record');const initial=await state();
  test('Fixture is the sourced 4.8 kg visit',initial.quickTraces.marsik.weight==='4.8');
  await go('discharge-preview');
  test('Initial explicit publication action enabled',await page.locator('[data-track="discharge-publish"]').isEnabled());
  await page.locator('[data-track="discharge-publish"]').click();
  await page.waitForFunction(k=>!!JSON.parse(localStorage.getItem(k)).visits.marsik.published,key);
  const published=await state();
  test('Actual click stores snapshot revision one',published.visits.marsik.published.revision===1);
  test('Snapshot excludes private note, history and diagnosis',['privateNote','history','diagnosis'].every(k=>!(k in published.visits.marsik.published.content)));
  await go('owner-home');
  const ownerBefore=await page.locator('[data-owner-home]').innerText();
  test('Owner shows published plan and 0.95 example',ownerBefore.includes(locale==='ru'?'Прекратить капли':'Stop the drops')&&ownerBefore.includes('0.95'));
  test('Owner has real telephone action',await page.locator('[data-owner-home] a[href^="tel:"]').count()>0);
  const changed=structuredClone(published);changed.visits.marsik.plan='V3 QA clinic draft: review before publishing';
  await load('owner-home',changed);
  test('Saved clinic edit leaves owner snapshot unchanged',await page.locator('[data-owner-home]').innerText()===ownerBefore);
  const blocked=structuredClone(published);blocked.visits.marsik.plan='';
  await load('discharge-preview',blocked);
  test('Empty saved plan blocks publication',await page.locator('[data-track="discharge-publish"]').isDisabled());
  await page.screenshot({path:`${root}/product-qa/${locale}-${width}-blocked.png`,fullPage:true});
  test('Blocked publication retains original snapshot',JSON.stringify((await state()).visits.marsik.published)===JSON.stringify(published.visits.marsik.published));
  await go('owner-home');
  test('Owner keeps last document after block',await page.locator('[data-owner-home]').innerText()===ownerBefore);
  const missing=structuredClone(published);missing.visits.marsik.published.content.concentration='';
  await load('owner-home',missing);
  const missingText=await page.locator('[data-owner-home]').innerText();
  test('Absent concentration asks clinic before medication',missingText.includes(locale==='ru'?'Перед применением':'before giving this medication'));
  test('Missing dose never presents 0.95 as administration amount',!missingText.includes('0.95'));
  test('Missing dose provides telephone fallback',await page.locator('[data-owner-home] a[href^="tel:"]').count()>0);
  await page.screenshot({path:`${root}/product-qa/${locale}-${width}-missing.png`,fullPage:true});
  await load('invoice-draft',initial);
  const invoice=await page.locator('[data-invoice-document]').innerText();
  test('Invoice contains the selected synthetic 1500 total',/1\s?500/.test(invoice));
  test('Invoice excludes clinic-only note',!invoice.includes(initial.visits.marsik.privateNote));
  await page.locator('[data-track="invoice-mark-paid"]').click();
  await page.waitForFunction(()=>document.querySelector('[data-track="invoice-mark-paid"]')?.getAttribute('data-paid')==='true');
  test('Reception explicitly records manual paid status',await page.locator('[data-track="invoice-mark-paid"]').isDisabled());
  await page.screenshot({path:`${root}/product-qa/${locale}-${width}-paid.png`,fullPage:true});
  await load('visit-quick-trace',initial);
  const stored=JSON.stringify((await state()).quickTraces.marsik);
  const weight=page.locator('[aria-labelledby="trace-weight"] input').first();
  await weight.fill('');await page.locator('[data-track="visit-quick-trace-save"]').click();await page.waitForTimeout(600);
  test('Invalid trace cannot change stored prescription',JSON.stringify((await state()).quickTraces.marsik)===stored);
  test('Invalid save focuses weight input',await weight.evaluate(e=>document.activeElement===e));
  await page.screenshot({path:`${root}/product-qa/${locale}-${width}-invalid-trace.png`,fullPage:true});
  test('No product runtime error',entry.errors.length===0);
  results.push(entry);await ctx.close();
}
await browser.close();
fs.writeFileSync(`${root}/product-qa/results.json`,JSON.stringify(results,null,2));
const tests=results.flatMap(e=>e.tests);console.log(`${tests.filter(t=>t.pass).length}/${tests.length} product assertions`);
if(tests.some(t=>!t.pass)) process.exitCode=1;
